#!/usr/bin/env node
/**
 * Inlines every JSON file under data/ into server/utils/seed-data.generated.ts
 * so Nitro/Vercel can serve seeds without filesystem or serverAssets.
 * Local/dev still prefers live files under data/; this is the serverless fallback.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dataRoot = path.join(root, 'data')
const outFile = path.join(root, 'server/utils/seed-data.generated.ts')

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...(await walk(full)))
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      files.push(full)
    }
  }
  return files
}

const files = (await walk(dataRoot)).sort()
const entries = []

for (const full of files) {
  const relativeKey = path.relative(dataRoot, full).split(path.sep).join('/')
  const raw = await fs.readFile(full, 'utf8')
  JSON.parse(raw) // validate
  entries.push(`  ${JSON.stringify(relativeKey)}: ${raw.trim()}`)
}

const banner = `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-seed-data.mjs — do not edit.
 * Source of truth: JSON files under data/
 * Regenerated on \`npm run prebuild\` / \`npm run generate:seeds\`.
 */
`

const body = `${banner}export const SEED_JSON: Record<string, unknown> = {\n${entries.join(',\n')}\n}\n`

await fs.mkdir(path.dirname(outFile), { recursive: true })
await fs.writeFile(outFile, body, 'utf8')
console.log(`Wrote ${entries.length} seeds → ${path.relative(root, outFile)}`)
